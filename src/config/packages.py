"""Встроенный список дополнительных RPM-пакетов для установки на хосты.

Редактируется перед сборкой. Имена - как для ``dnf install``.
Мастер настройки предлагает их на шаге «Пакеты» (в группе «Удалённые»)
и устанавливает через ``dnf install -y`` (fallback ``apt-get install -y``)
на каждом отмеченном хосте.
"""

# Пакеты, предлагаемые мастером по умолчанию (все включены чекбоксами).
# Для DBus-входа (org.mos.auth) на MOS/ROSA Linux.
EXTRA_PACKAGES = [
    "mos-auth-dbus-conf",
]

# Зависимости пакетов: при выборе основного пакета в мастере зависимые
# добавляются автоматически и показываются информационной меткой под
# основным чекбоксом. Имена - по доке MOS12 (it-help-school.ru):
# mos-auth-core - база подсистемы и утилита mos-auth-config,
# mos-auth-folders - сетевые папки (ставит базовая установка из доки).
PACKAGE_DEPENDENCIES = {
    "mos-auth-dbus-conf": [
        "mos-auth-core",
        "mos-auth-folders",
    ],
}

# Команды, выполняемые после установки пакета на хосте
# (через тот же SSH/sudo-канал, что и установка).
# Ключ - пакет; значение - shell-команда.
# Выполняется для всех выбранных пакетов. Ошибка команды - ошибка шага
# только для пакета, который установил текущий запуск мастера; для уже
# стоявшего она лишь записывается в подробности (повторный
# `mos-auth-config enable` на настроенном хосте отвечает «Уже настроено»).
PACKAGE_POST_INSTALL = {
    "mos-auth-dbus-conf": "mos-auth-config enable",
}
